/**
 * Writes one static HTML file per shareable route, each with its own title and Open Graph
 * tags, because link-preview bots (WhatsApp, Telegram, X…) never run JavaScript:
 *   dist/galeria/index.html
 *   dist/disco/<id>/index.html   (×500, og:image = dist/og/<id>.jpg from og-images.ts)
 * They are copies of dist/index.html (same app bundle) with the <!--meta:start…end--> block and
 * <title> replaced. Besides the preview, deep links now answer 200 instead of the 404.html
 * fallback, which some crawlers refuse.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ALBUMS } from '../src/data/albums';
import { rarityForRank } from '../src/rarity';

const SITE = 'https://ltmleo.github.io/disk-discovery/';
const DIST = fileURLToPath(new URL('../dist/', import.meta.url));
const shell = readFileSync(`${DIST}index.html`, 'utf8');
if (!/<!--meta:start[\s\S]*?<!--meta:end-->/.test(shell)) throw new Error('index.html lacks the meta:start/end block');

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

interface Meta {
  path: string; // relative to SITE, with trailing slash
  title: string;
  description: string;
  image: string; // relative to SITE
  imageAlt: string;
}

function page(m: Meta): string {
  const url = SITE + m.path;
  const block = `<!--meta:start (generated by scripts/static-pages.ts) -->
    <meta name="description" content="${esc(m.description)}" />
    <link rel="canonical" href="${url}" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="Disk Discovery" />
    <meta property="og:locale" content="pt_BR" />
    <meta property="og:url" content="${url}" />
    <meta property="og:title" content="${esc(m.title)}" />
    <meta property="og:description" content="${esc(m.description)}" />
    <meta property="og:image" content="${SITE}${m.image}" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta property="og:image:alt" content="${esc(m.imageAlt)}" />
    <meta name="twitter:card" content="summary_large_image" />
    <!--meta:end-->`;
  return shell
    .replace(/<!--meta:start[\s\S]*?<!--meta:end-->/, block)
    .replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(m.title)}</title>`);
}

function write(m: Meta) {
  mkdirSync(DIST + m.path, { recursive: true });
  writeFileSync(`${DIST}${m.path}index.html`, page(m));
}

write({
  path: 'galeria/',
  title: 'Galeria · Disk Discovery',
  description: 'Todos os 500 maiores discos da Rolling Stone em cartas: quais você já descobriu?',
  image: 'og/site.jpg',
  imageAlt: 'Pacote do Disk Discovery com um disco de vinil',
});

for (const a of ALBUMS) {
  const r = rarityForRank(a.rank);
  const hook = a.tagline ? ` ${a.tagline}` : '';
  write({
    path: `disco/${a.id}/`,
    title: `${a.title} · ${a.artist} — Disk Discovery`,
    description: `${'★'.repeat(r.stars)} ${r.label} · #${a.rank} dos 500 maiores discos da Rolling Stone (${a.year}).${hook}`,
    image: `og/${a.id}.jpg`,
    imageAlt: `Carta ${r.label} de ${a.title}, de ${a.artist}, com a capa do disco`,
  });
}
// Sitemap for search engines (listed in the home's robots.txt, per the ltm-novo-site skill).
const urls = ['', 'galeria/', ...ALBUMS.map((a) => `disco/${a.id}/`)];
writeFileSync(
  `${DIST}sitemap.xml`,
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls
    .map((u) => `  <url><loc>${SITE}${u}</loc></url>`)
    .join('\n')}\n</urlset>\n`,
);
console.log(`static pages: galeria + ${ALBUMS.length} albums, sitemap with ${urls.length} urls`);
